"""Assemble reports/report_draft.md from experiments/report_template.md.

Every number in the report comes from a file produced by the experiment scripts.
Placeholders in the template:

    {{table:e1_summary}}            the markdown table reports/tables/e1_summary.md
    {{fig:e1_boxplots|Caption}}     an image reference to reports/figures/e1_boxplots.png
    {{num:e2.best_baseline}}        a value looked up in the merged results (dotted path)
    {{num:e1.summary.lightgbm.roc_auc|.3f}}   ... with a format spec
    {{pct:e6.precision}}            a fraction shown as a percentage
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from common import FIGURES, REPORTS, RESULTS, ROOT, TABLES

TEMPLATE = ROOT / "experiments" / "report_template.md"
OUT = REPORTS / "report_draft.md"


def load_results() -> dict:
    data: dict = {}
    for name, key in [("summary_eval.json", None), ("summary_system.json", "e7"), ("e6_spotcheck.json", "e6"),
                      ("demo_cache.json", "demo"), ("ingest.json", "ingest"), ("run_info.json", "run")]:
        p = RESULTS / name
        if not p.exists():
            continue
        v = json.loads(p.read_text())
        if key is None:
            data.update(v)
        else:
            data[key] = v
    if "ingest" in data:
        ing = data["ingest"]
        data["dataset"] = {
            "repos": len(ing),
            "commits": sum(r["commits"] for r in ing),
            "bugfix_commits": sum(r["bugfix_commits"] for r in ing),
            "files_last": sum(r["files_last"] for r in ing),
            "ingest_seconds": sum(r["wall_seconds"] for r in ing),
            "max_peak_mb": max(r["peak_rss_mb"] for r in ing),
        }
    return data


def lookup(data: dict, path: str):
    cur = data
    for part in path.split("."):
        if isinstance(cur, list):
            cur = cur[int(part)]
        else:
            cur = cur[part]
    return cur


def render(template: str, data: dict) -> str:
    def table(m: re.Match) -> str:
        p = TABLES / f"{m.group(1)}.md"
        if not p.exists():
            return f"*[missing table {m.group(1)}: run experiments/run_all.py]*"
        lines = p.read_text(encoding="utf-8").splitlines()
        return "\n".join(line for line in lines if not line.startswith("<!--")).strip()

    def fig(m: re.Match) -> str:
        name, _, caption = m.group(1).partition("|")
        if not (FIGURES / f"{name}.png").exists():
            return f"*[missing figure {name}]*"
        return f"![{caption}](figures/{name}.png)\n\n*{caption}*"

    def num(m: re.Match) -> str:
        path, _, spec = m.group(2).partition("|")
        try:
            v = lookup(data, path)
        except (KeyError, IndexError, TypeError):
            return f"[missing {path}]"
        if m.group(1) == "pct":
            return f"{float(v) * 100:{spec or '.1f'}}%"
        if spec and isinstance(v, (int, float)):
            return f"{v:{spec}}"
        return str(v)

    out = re.sub(r"\{\{table:([\w-]+)\}\}", table, template)
    out = re.sub(r"\{\{fig:([^}]+)\}\}", fig, out)
    out = re.sub(r"\{\{(num|pct):([^}]+)\}\}", num, out)
    return out


def run() -> Path:
    data = load_results()
    text = render(TEMPLATE.read_text(encoding="utf-8"), data)
    header = ("<!-- GENERATED by experiments/make_report.py from experiments/report_template.md. "
              "Edit the template, not this file. -->\n\n")
    OUT.write_text(header + text, encoding="utf-8")
    missing = re.findall(r"\[missing [^\]]+\]", text)
    print(f"  wrote {OUT} ({len(text.split())} words){'; MISSING: ' + ', '.join(missing) if missing else ''}")
    return OUT


if __name__ == "__main__":
    run()
