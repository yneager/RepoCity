# ---------------------------------------------------------------- helpers
def fmt(mean: float, std: float) -> str:
    if np.isnan(mean):
        return "n/a"
    return f"{mean:.3f} ± {std:.3f}" if not np.isnan(std) else f"{mean:.3f}"


def write_table(df: pd.DataFrame, name: str, caption: str) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    df.to_csv(TABLES / f"{name}.csv", index=False)
    md = [f"<!-- generated by experiments/stage_report.py: {caption} -->", "", "| " + " | ".join(df.columns) + " |",
          "|" + "|".join("---" for _ in df.columns) + "|"]
    for _, row in df.iterrows():
        md.append("| " + " | ".join(str(v) for v in row.values) + " |")
    (TABLES / f"{name}.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def cliffs_delta(a: np.ndarray, b: np.ndarray) -> float:
    a, b = np.asarray(a), np.asarray(b)
    gt = (a[:, None] > b[None, :]).sum()
    lt = (a[:, None] < b[None, :]).sum()
    return float((gt - lt) / (len(a) * len(b)))


def cliff_magnitude(d: float) -> str:
    d = abs(d)
    return "negligible" if d < 0.147 else "small" if d < 0.33 else "medium" if d < 0.474 else "large"


def holm(pvals: list[float]) -> list[float]:
    order = np.argsort(pvals)
    adj = np.empty(len(pvals))
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, (len(pvals) - rank) * pvals[i])
        adj[i] = min(1.0, running)
    return adj.tolist()


def save(fig, name: str) -> None:
    FIGURES.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURES / f"{name}.png")
    plt.close(fig)


# ---------------------------------------------------------------- E1
def e1_tables(e1: pd.DataFrame) -> dict:
    out = {}
    agg = e1.groupby(["repo", "method"])[METRICS].agg(["mean", "std"])
    repos = list(dict.fromkeys(e1["repo"]))
    for metric in METRICS:
        rows = []
        for r in repos:
            row = {"Repository": r}
            for m in METHODS:
                if (r, m) in agg.index:
                    row[METHOD_LABELS[m]] = fmt(agg.loc[(r, m), (metric, "mean")], agg.loc[(r, m), (metric, "std")])
            rows.append(row)
        write_table(pd.DataFrame(rows), f"e1_{metric}", f"E1 {METRIC_LABELS[metric]} per repository, mean ± std over cutoffs")
    # overall summary: mean over all (repo, cutoff) observations
    summ = []
    for m in METHODS:
        d = e1[e1["method"] == m]
        row = {"Method": METHOD_LABELS[m]}
        for metric in METRICS:
            row[METRIC_LABELS[metric]] = fmt(d[metric].mean(), d[metric].std())
        summ.append(row)
    write_table(pd.DataFrame(summ), "e1_summary", "E1 all repositories pooled (mean ± std over repo x cutoff)")
    out["summary"] = {m: {k: float(e1[e1["method"] == m][k].mean()) for k in METRICS} for m in METHODS}
    # dataset table
    ds = e1[e1["method"] == "random"].groupby(["repo", "language"]).agg(
        cutoffs=("cutoff", "count"), first_cutoff=("cutoff", "min"), last_cutoff=("cutoff", "max"),
        files=("n_files", "mean"), positives=("n_pos", "mean"), train_rows=("n_train", "mean"),
    ).reset_index()
    ds["positive rate"] = (ds["positives"] / ds["files"]).map(lambda v: f"{v:.1%}")
    for c in ("files", "positives", "train_rows"):
        ds[c] = ds[c].round(1)
    write_table(ds, "e1_dataset", "Evaluation windows per repository (means over cutoffs)")
    return out


